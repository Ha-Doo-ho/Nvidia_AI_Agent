#1. L2 정규화란 무엇인가?
# 모델이 학습을 하다 보면, 정답을 맞히기 위해 특정 픽셀이나 지엽적인 특징 하나에만 엄청나게 높은 가중치(Weight)를 부여하는 꼼수를 부리기 시작합니다.
# L2 정규화는 이런 꼼수를 막기 위해 "가중치 값이 너무 커지면 손실(Loss) 점수에 벌점을 더하겠다"는 규칙을 추가하는 것입니다.수식으로는 기존 손실 함수에 가중치($w$)의 제곱합을 더합니다. 
# (수학적으로 'Ridge(릿지)' 규제라고도 부릅니다.)

# 가중치를 제곱해서 벌점을 매기기 때문에, 튀는 값(너무 큰 가중치)이 생기면 벌점이 기하급수적으로 늘어납니다. 결과적으로 모델은 특정 힌트 하나에 의존하지 않고, 이미지의 여러 특징을 골고루 적당히 참고하는 둥글둥글하고 안정적인 모델로 변합니다.
# 과적합을 막는 용도로 사용할 수 있기에 과적합이 가장 일어날 가능성이 있는 Dense(정확히는 Flatten 직후의 Dense)에서 L2 규제를 거는 것이 가장 일반적이다. (보통 1e-4) 
# Conv층에 거는 경우도 있다. 여러 Conv층이 있겠지만 깊은 Conv층에 사용한다. 아무래도 가중치가 공유되니까, 파라미터 개수는 적어서 과적합에 강하긴 하다. 
# 층이 "매우" 깊어지면 과적합이 발생할 수도 있다. 그래서 보통 Dense층보다 규제 강도를 더 적게 한다. (1e-5)
